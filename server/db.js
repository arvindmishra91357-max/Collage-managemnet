require('dotenv').config();
const path = require('path');
const bcrypt = require('bcryptjs');

let isPostgres = false;
let pgPool = null;
let sqliteDb = null;

const DB_PATH = path.join(__dirname, '..', 'college_portal.sqlite');

if (process.env.DATABASE_URL && process.env.DATABASE_URL.trim() !== '') {
  try {
    const { Pool } = require('pg');
    pgPool = new Pool({
      connectionString: process.env.DATABASE_URL,
      ssl: process.env.NODE_ENV === 'production' ? { rejectUnauthorized: false } : false
    });
    isPostgres = true;
    console.log('[DB] Using PostgreSQL / Supabase connection');
  } catch (err) {
    console.warn('[DB] PostgreSQL init failed, falling back to SQLite:', err.message);
    isPostgres = false;
  }
}

if (!isPostgres) {
  const sqlite3 = require('sqlite3').verbose();
  sqliteDb = new sqlite3.Database(DB_PATH);
  console.log('[DB] Using SQLite database at:', DB_PATH);
}

// Unified query helpers
const formatSqlForPg = (sql) => {
  let paramIndex = 1;
  return sql.replace(/\?/g, () => `$${paramIndex++}`);
};

const query = (sql, params = []) => {
  if (isPostgres) {
    const formatted = formatSqlForPg(sql);
    return pgPool.query(formatted, params).then(res => res.rows);
  }
  return new Promise((resolve, reject) => {
    sqliteDb.all(sql, params, (err, rows) => {
      if (err) reject(err);
      else resolve(rows || []);
    });
  });
};

const get = (sql, params = []) => {
  if (isPostgres) {
    const formatted = formatSqlForPg(sql);
    return pgPool.query(formatted, params).then(res => res.rows[0] || null);
  }
  return new Promise((resolve, reject) => {
    sqliteDb.get(sql, params, (err, row) => {
      if (err) reject(err);
      else resolve(row || null);
    });
  });
};

const run = (sql, params = []) => {
  if (isPostgres) {
    let formatted = formatSqlForPg(sql);
    // If it's an INSERT and has no RETURNING clause, add RETURNING id
    if (/^\s*INSERT\s+INTO/i.test(formatted) && !/RETURNING/i.test(formatted)) {
      formatted += ' RETURNING id';
    }
    return pgPool.query(formatted, params).then(res => {
      const id = res.rows && res.rows[0] ? res.rows[0].id : null;
      return { id, changes: res.rowCount };
    });
  }
  return new Promise((resolve, reject) => {
    sqliteDb.run(sql, params, function (err) {
      if (err) reject(err);
      else resolve({ id: this.lastID, changes: this.changes });
    });
  });
};

